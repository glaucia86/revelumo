const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { app, BrowserWindow } = require('electron');
const root = path.resolve(__dirname, '..'), run = path.resolve(process.argv[2]);
const appRoot = path.join(root, 'out', `Revelumo-${process.platform}-${process.arch}`, 'resources', 'app.asar');
fs.mkdirSync(run, { recursive: true }); app.setPath('userData', path.join(run, 'user-data'));
const fail = error => { console.error(error.stack || error); app.exit(1); };
process.on('uncaughtException', fail); process.on('unhandledRejection', fail);
app.on('window-all-closed', () => {});
const timer = setTimeout(() => fail(new Error('Circuit harness deadline exceeded')), 120000);
app.whenReady().then(async () => {
  const sentinel = new BrowserWindow({ show: false, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
  await sentinel.loadURL('about:blank');
  const license = fs.readFileSync(path.join(appRoot, '.vite/renderer/main_window/licenses/xmldom-MIT.txt'));
  assert.deepEqual(license, fs.readFileSync(path.join(root, 'public/licenses/xmldom-MIT.txt')));
  const owned = []; const sentinelPid = sentinel.webContents.getOSProcessId();
  app.on('browser-window-created', (_event, window) => { const record = { window, pid: 0 }; owned.push(record); window.webContents.on('dom-ready', () => { record.pid = window.webContents.getOSProcessId(); assert.notEqual(record.pid, sentinelPid); }); });
  const { exportJpeg } = require(path.join(appRoot, '.vite/build/jpeg-export-service.cjs'));
  const fixture = path.join(root, 'test/fixtures/export');
  const expected = JSON.parse(fs.readFileSync(path.join(fixture, 'circuit-expected.json'), 'utf8'));
  const sourcePath = path.join(run, 'source.jpg'); fs.copyFileSync(path.join(fixture, 'circuit-source.jpg'), sourcePath, fs.constants.COPYFILE_EXCL);
  const destination = path.join(run, 'published.jpg');
  const before = fs.statSync(sourcePath, { bigint: true });
  const request = { sourcePath, sourceSha256: expected.sourceSha256, recipe: expected.recipe, destination, originalPaths: [], protectedDirectories: [path.join(run, 'catalog')], maximumOutputBytes: 32 * 1024 * 1024 };
  const result = await exportJpeg(request);
  assert.equal(result.path, destination); assert.equal(result.cleanupPending, false);
  assert.equal(result.bytesWritten, fs.statSync(destination).size);
  const after = fs.statSync(sourcePath, { bigint: true }); assert.equal(before.ino, after.ino); assert.equal(before.dev, after.dev);
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(sourcePath)).digest('hex'), expected.sourceSha256);
  assert.equal(await sentinel.webContents.executeJavaScript('6 * 7'), 42);
  assert.deepEqual([result.width, result.height], expected.outputDimensions);
  const publishedHash = crypto.createHash('sha256').update(fs.readFileSync(destination)).digest('hex');
  await assert.rejects(exportJpeg(request), { code: 'DESTINATION_EXISTS' });
  await assert.rejects(exportJpeg({ ...request, destination: sourcePath }), { code: 'PROTECTED_DESTINATION' });
  const alias = path.join(run, 'source-hardlink.jpg'); fs.linkSync(sourcePath, alias);
  await assert.rejects(exportJpeg({ ...request, destination: alias }), { code: 'DESTINATION_EXISTS' });
  const aliasStat = fs.statSync(alias, { bigint: true }); assert.equal(aliasStat.ino, before.ino); assert.equal(aliasStat.dev, before.dev);
  await assert.rejects(exportJpeg({ ...request, sourceSha256: '0'.repeat(64), destination: path.join(run, 'changed.jpg') }), { code: 'IDENTITY_MISMATCH' });
  await assert.rejects(exportJpeg({ ...request, recipe: { ...expected.recipe, crop: null } }), { code: 'UNSUPPORTED_RECIPE' });
  await assert.rejects(exportJpeg({ ...request, destination: path.join(run, 'canceled.jpg') }, AbortSignal.abort()), { code: 'CANCELED' });
  assert.equal(fs.existsSync(path.join(run, 'changed.jpg')), false); assert.equal(fs.existsSync(path.join(run, 'canceled.jpg')), false);
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(destination)).digest('hex'), publishedHash);
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(alias)).digest('hex'), expected.sourceSha256);
  for (const record of owned) { assert.ok(record.window.isDestroyed()); assert.ok(record.pid > 0); assert.ok(!app.getAppMetrics().some(item => item.pid === record.pid)); }
  console.log('PASS packaged notice, aliases/no-clobber, auth/crop/cancel and renderer cleanup');
  console.log('CIRCUIT PASS', JSON.stringify(result));
  fs.writeFileSync(path.join(run, 'result.json'), JSON.stringify({ result, sourcePath, destination, expected: path.join(fixture, 'circuit-expected.json') }, null, 2));
  if (process.argv[3] === 'memory') await require('./jpeg-export-circuit-memory.cjs')({ exportJpeg, app, sentinel, root, run });
  clearTimeout(timer); sentinel.destroy(); app.exit(0);
}).catch(fail);
